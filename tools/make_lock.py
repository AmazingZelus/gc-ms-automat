"""Create requirements/runtime.lock.txt: exact versions + SHA-256 hashes of all
Windows wheels. Run after changing requirements/runtime.in:

    python tools/make_lock.py

Works on any operating system (it downloads the Windows wheels for the check).
"""

import hashlib
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_config import PYTHON_TAG, WHEEL_PLATFORM  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
IN_FILE = ROOT / "requirements" / "runtime.in"
LOCK_FILE = ROOT / "requirements" / "runtime.lock.txt"


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        # This downloads every needed wheel for Windows 64-bit and our Python version.
        subprocess.run([
            sys.executable, "-m", "pip", "download", "-q", "-d", tmp,
            "--only-binary=:all:", "--platform", WHEEL_PLATFORM,
            "--python-version", PYTHON_TAG[0] + "." + PYTHON_TAG[1:], "--implementation", "cp",
            "-r", str(IN_FILE),
        ], check=True)

        # This writes "name==version --hash=sha256:..." for each downloaded wheel.
        lines = ["# GENERATED by tools/make_lock.py from runtime.in - do not edit by hand.",
                 f"# Target: CPython {PYTHON_TAG}, {WHEEL_PLATFORM}."]
        for wheel in sorted(Path(tmp).glob("*.whl"), key=lambda p: p.name.lower()):
            name, version = wheel.name.split("-")[:2]
            digest = hashlib.sha256(wheel.read_bytes()).hexdigest()
            lines.append(f"{name.lower()}=={version} --hash=sha256:{digest}")
        LOCK_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Written {LOCK_FILE}")


if __name__ == "__main__":
    main()
